#!/usr/bin/env python3
"""Generate searchable, decoded metadata from the unchanged UCUM catalog."""
import argparse
import json
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = ET.parse(ROOT / "standards/ucum-essence.xml").getroot()
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    rows = []
    for atom in list(root.findall("{*}base-unit")) + list(root.findall("{*}unit")):
        names = ", ".join(quote(name.text or "") for name in atom.findall("{*}name"))
        fields = [
            "code: " + quote(atom.get("Code")),
            "insensitive_code: " + quote(atom.get("CODE").upper()),
            "names: [" + names + "]",
            "property: " + quote(atom.find("{*}property").text or ""),
            "metric: " + str(atom.get("isMetric", "yes") == "yes").lower(),
            "arbitrary: " + str(atom.get("isArbitrary") == "yes").lower(),
            "special: " + str(atom.get("isSpecial") == "yes").lower(),
        ]
        rows.extend(["    {", *["      " + field + "," for field in fields], "    },"])
    content = "///|\n// Generated by scripts/generate_metadata.py from the pinned catalog.\nfn metadata_rows() -> Array[UnitInfo] {\n  [\n" + "\n".join(rows) + "\n  ]\n}\n"
    destination = ROOT / "metadata_data.mbt"
    if args.check:
        if destination.read_text(encoding="utf-8") != content:
            raise SystemExit("Generated metadata is stale")
    else:
        destination.write_bytes(content.encode("utf-8"))


if __name__ == "__main__":
    main()
